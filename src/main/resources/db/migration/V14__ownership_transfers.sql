-- Server-ownership transfer offers: a PENDING row waits for the recipient's accept or
-- decline (and survives restarts — the recipient learns about it from the REST snapshot
-- at session start), any later offer silently replaces the previous PENDING one, and
-- accept swaps the OWNER role between the two users. History rows (ACCEPTED/DECLINED/
-- CANCELLED) stay as the audit trail.
CREATE TABLE ownership_transfer (
    id bigint NOT NULL,
    from_user_id bigint NOT NULL,
    to_user_id bigint NOT NULL,
    status character varying(16) NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT ownership_transfer_pkey PRIMARY KEY (id),
    CONSTRAINT ownership_transfer_from_fkey FOREIGN KEY (from_user_id) REFERENCES public.users (id),
    CONSTRAINT ownership_transfer_to_fkey FOREIGN KEY (to_user_id) REFERENCES public.users (id)
);

-- IDENTITY block is MANDATORY (the V4/V9 lesson): the entity declares @GeneratedValue(IDENTITY),
-- but on the Flyway-owned live schema inserts fail without it. H2 tests regenerate the schema
-- from entities, so only the real Postgres deployment sees the miss.
ALTER TABLE ownership_transfer ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.ownership_transfer_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);
