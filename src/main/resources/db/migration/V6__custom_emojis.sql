-- Custom emojis (phase 1: flat server-scoped catalog; packs land with stickers in phase 2).
-- The instance IS the server (single-tenant) — no server_id column. Messages reference
-- emojis only as ":name:" plain text; there is no FK from messages (deleting an emoji
-- degrades old messages to plaintext — accepted Discord-style tradeoff).
CREATE TABLE custom_emojis (
    id bigint NOT NULL,
    name character varying(32) NOT NULL,
    file_key character varying(512) NOT NULL,
    uploaded_by bigint NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT custom_emojis_pkey PRIMARY KEY (id),
    CONSTRAINT custom_emojis_name_unique UNIQUE (name),
    CONSTRAINT custom_emojis_file_key_unique UNIQUE (file_key),
    CONSTRAINT custom_emojis_uploaded_by_fkey FOREIGN KEY (uploaded_by) REFERENCES public.users (id)
);

-- IDENTITY block is MANDATORY (the V4 lesson): the entity declares @GeneratedValue(IDENTITY),
-- but on the Flyway-owned live schema inserts fail without it. H2 tests regenerate the schema
-- from entities, so only the real Postgres deployment sees the miss.
ALTER TABLE custom_emojis ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.custom_emojis_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);
