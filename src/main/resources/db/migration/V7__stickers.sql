-- Custom stickers with packs (phase 2 of custom expressions). Packs are a grouping for the
-- picker/settings UI; stickers are referenced by id only at SEND time — messages carry the
-- sticker DENORMALIZED (sticker_name/sticker_file_key copied from the catalog row), so there
-- is no FK from messages (deleting a sticker degrades old messages to a client-side
-- tombstone — the accepted emoji tradeoff). Sticker names are unique PER PACK, not globally.
CREATE TABLE sticker_packs (
    id bigint NOT NULL,
    name character varying(32) NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT sticker_packs_pkey PRIMARY KEY (id),
    CONSTRAINT sticker_packs_name_unique UNIQUE (name)
);

-- IDENTITY block is MANDATORY (the V4 lesson): the entity declares @GeneratedValue(IDENTITY),
-- but on the Flyway-owned live schema inserts fail without it. H2 tests regenerate the schema
-- from entities, so only the real Postgres deployment sees the miss.
ALTER TABLE sticker_packs ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.sticker_packs_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

CREATE TABLE stickers (
    id bigint NOT NULL,
    name character varying(32) NOT NULL,
    file_key character varying(512) NOT NULL,
    pack_id bigint NOT NULL,
    uploaded_by bigint NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT stickers_pkey PRIMARY KEY (id),
    CONSTRAINT stickers_pack_name_unique UNIQUE (pack_id, name),
    CONSTRAINT stickers_file_key_unique UNIQUE (file_key),
    CONSTRAINT stickers_pack_fkey FOREIGN KEY (pack_id) REFERENCES public.sticker_packs (id),
    CONSTRAINT stickers_uploaded_by_fkey FOREIGN KEY (uploaded_by) REFERENCES public.users (id)
);

ALTER TABLE stickers ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.stickers_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

-- The denormalized copy on messages (both nullable — populated only at send/forward time;
-- no FK: dangling by design, like replied_to_id and the forward_* origin fields).
ALTER TABLE messages ADD COLUMN sticker_name character varying(32);
ALTER TABLE messages ADD COLUMN sticker_file_key character varying(512);
