-- Invite links (single-use registration secrets). A non-empty instance only accepts
-- registrations presenting a valid unused unexpired unrevoked secret; a fresh instance
-- bootstraps its OWNER without one (the pre-provisioning path). Used/expired/revoked
-- rows stay in place as the audit trail of one-time secrets (one row per registration).
CREATE TABLE invites (
    id bigint NOT NULL,
    secret character varying(64) NOT NULL,
    created_by bigint NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    expires_at timestamp(6) with time zone NOT NULL,
    revoked boolean NOT NULL,
    used boolean NOT NULL,
    used_by bigint,
    used_at timestamp(6) with time zone,
    CONSTRAINT invites_pkey PRIMARY KEY (id),
    CONSTRAINT invites_secret_unique UNIQUE (secret),
    CONSTRAINT invites_created_by_fkey FOREIGN KEY (created_by) REFERENCES public.users (id),
    CONSTRAINT invites_used_by_fkey FOREIGN KEY (used_by) REFERENCES public.users (id)
);

-- IDENTITY block is MANDATORY (the V4 lesson): the entity declares @GeneratedValue(IDENTITY),
-- but on the Flyway-owned live schema inserts fail without it. H2 tests regenerate the schema
-- from entities, so only the real Postgres deployment sees the miss.
ALTER TABLE invites ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.invites_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

-- Retroactive TTL lives on the singleton profile (the storage_* pattern: int default,
-- null on rows predating the column resolves to the code default in the controller).
ALTER TABLE server_profile ADD COLUMN invite_ttl_hours integer DEFAULT 24;
